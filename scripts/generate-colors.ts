const values: Record<string,string> = {};
for (const [group, items] of Object.entries(colors)) {
  if (typeof items === 'string') { values[names[group] || group] = items; continue; }
  for (const [name, value] of Object.entries(items)) {
    if (typeof value === 'string') values[names[`${group}.${name}`] || `${group}-${name}`] = value;
    else for (const [part, color] of Object.entries(value)) values[names[`${group}.${name}.${part}`] || `${group}-${name}-${part}`] = color;
  }
}
const declarations = Object.entries(values).map(([name,value]) => `  --${name}: ${value};`).join('\n');
